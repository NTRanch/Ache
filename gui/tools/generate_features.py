#!/usr/bin/env python3
"""Generate gui/data/features.tsv for ache-gui.

Source of record for device capabilities: the buttplug device config
(build-config/buttplug-device-config-v5.json) inside the pinned
buttplug_server_device_config crate in primo's cargo registry — the
same embedded config ache's runtime loads (ache inherits it wholesale;
Phase 0 census). NO data is invented: a device whose config cannot be
matched gets match=none and an empty feature list, and the GUI says so.

Matching, in order (first hit wins, recorded in the `match` column):
  exact   — normalised config name == normalised "brand + device"
  gen     — as exact, after stripping a trailing generation token
            (e.g. catalogue "Edge 2" vs config "Lovense Edge")
  name    — normalised config name == normalised device name alone
  default — the protocol defaults' name matches as above and the
            device is a generic-config (bucket A-g) row
Configurations without their own `features` inherit their protocol
defaults' features (that is how the buttplug loader resolves them).

Family (form factor) is classified from the catalogue's IoST device
type, first listed type wins, via FAMILY_BY_TYPE below. The family is
what the image/turntable pipeline and the trial's "kind" limits key
on; it is presentation metadata, not a capability claim.
"""
import glob
import json
import re
import sys
from pathlib import Path

FAMILY_BY_TYPE = {
    "Love Egg": "egg",
    "Insertable Vibrator": "insertable",
    "Rabbit": "rabbit",
    "Buttplug": "plug",
    "Panty Vibrator": "panty",
    "Suction Vibrator": "suction",
    "Butterfly": "butterfly",
    "Kegel": "kegel",
    "Kegel Wedge": "kegel",
    "Bullet": "bullet",
    "Wand": "wand",
    "Clip Vibrator": "clip",
    "External Vibrator": "external",
    "Ride-on Vibrator": "rideon",
    "Prostate Vibrator": "prostate",
    "Nipple Massager": "nipple",
    "Nipple Clamps": "nipple",
    "Breast cups": "nipple",
    "Anal Beads": "beads",
    "Sound": "sound",
    "Vibrator Controller": "controller",
}


def norm(s: str) -> str:
    return re.sub(r"[^a-z0-9]", "", s.lower())


def strip_gen(s: str) -> str:
    # Drop a trailing generation token: "edge2", "lush3", "v2"...
    return re.sub(r"(v?\d+)$", "", s)


def features_of(cfg, defaults):
    feats = cfg.get("features")
    if feats is None and defaults is not None:
        feats = defaults.get("features")
    outputs, inputs = [], []
    for f in feats or []:
        desc = (f.get("description") or "").replace("\t", " ").replace(",", ";")
        if "output" in f:
            for kind, spec in f["output"].items():
                val = spec.get("value", [0, 0])
                if isinstance(val, list) and len(val) == 2 and isinstance(val[0], int):
                    outputs.append(f"{kind}:{val[0]}..{val[1]}:{desc}")
                else:
                    outputs.append(f"{kind}:0..0:{desc}")
        if "input" in f:
            for kind in f["input"]:
                inputs.append(kind)
    return outputs, inputs


def main() -> int:
    gui_dir = Path(__file__).resolve().parent.parent
    candidates = sorted(
        glob.glob(
            str(
                Path.home()
                / ".cargo/registry/src/*/buttplug_server_device_config-*/build-config/buttplug-device-config-v5.json"
            )
        )
    )
    if not candidates:
        print("buttplug device config v5 not found in cargo registry", file=sys.stderr)
        return 1
    config = json.loads(Path(candidates[-1]).read_text())
    print(f"config source: {candidates[-1]}")

    by_full, by_name, defaults_by_proto = {}, {}, {}
    for proto, pcfg in config["protocols"].items():
        defaults = pcfg.get("defaults")
        if defaults:
            defaults_by_proto[proto] = defaults
        for c in pcfg.get("configurations") or []:
            by_full.setdefault(norm(c["name"]), (c, defaults))
            by_name.setdefault(norm(c["name"].split(" ", 1)[-1]), (c, defaults))
            by_name.setdefault(norm(c["name"]), (c, defaults))

    rows = []
    for line in (gui_dir / "data/catalogue.tsv").read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        rows.append(line.split("\t"))

    out_lines = [
        "# Generated by tools/generate_features.py from the pinned buttplug",
        "# device config v5 (see that file for provenance). Do not hand-edit.",
        "# brand \\t device \\t family \\t match \\t outputs \\t inputs",
    ]
    tally = {"exact": 0, "gen": 0, "name": 0, "default": 0, "none": 0}
    fam_tally = {}
    for brand, device, dtype, bucket, *_rest in rows:
        first_type = dtype.split(",")[0].strip()
        family = FAMILY_BY_TYPE.get(first_type, "other")
        fam_tally[family] = fam_tally.get(family, 0) + 1
        full = norm(brand + " " + device)
        hit, match = None, "none"
        if full in by_full:
            hit, match = by_full[full], "exact"
        elif strip_gen(full) in by_full:
            hit, match = by_full[strip_gen(full)], "gen"
        elif norm(device) in by_name:
            hit, match = by_name[norm(device)], "name"
        elif bucket == "A-g":
            # Generic-config rows resolve through protocol defaults whose
            # display name is the generic device name; try defaults names.
            for proto, defaults in defaults_by_proto.items():
                if norm(defaults.get("name", "")) == full or norm(
                    defaults.get("name", "")
                ) == strip_gen(full):
                    hit, match = (defaults, defaults), "default"
                    break
        outputs, inputs = ([], [])
        if hit:
            outputs, inputs = features_of(hit[0], hit[1])
        tally[match] += 1
        out_lines.append(
            "\t".join(
                [
                    brand,
                    device,
                    family,
                    match,
                    ",".join(outputs),
                    ",".join(sorted(set(inputs))),
                ]
            )
        )
    (gui_dir / "data/features.tsv").write_text("\n".join(out_lines) + "\n")
    print(f"rows: {len(rows)}  match tally: {tally}")
    print(f"families: {dict(sorted(fam_tally.items(), key=lambda kv: -kv[1]))}")
    with_feats = sum(1 for l in out_lines[3:] if l.split("\t")[4])
    print(f"rows with >=1 output feature: {with_feats}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
